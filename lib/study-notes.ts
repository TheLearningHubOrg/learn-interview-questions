export interface NoteItem {
  trackSlug: string;
  trackTitle: string;
  questionNumber: number;
  questionTitle: string;
  content: string;
  updatedAt: number;
}

const NOTES_STORAGE_KEY = 'interviewhub_notes';
export const NOTES_UPDATE_EVENT = 'interviewhub_notes_update';

function getStorageMap(): Record<string, NoteItem> {
  if (typeof window === 'undefined') return {};
  try {
    const raw = localStorage.getItem(NOTES_STORAGE_KEY);
    if (!raw) return {};
    return JSON.parse(raw) as Record<string, NoteItem>;
  } catch {
    return {};
  }
}

function makeKey(trackSlug: string, questionNumber: number): string {
  return `${trackSlug}:${questionNumber}`;
}

export function getQuestionNote(trackSlug: string, questionNumber: number): string {
  const map = getStorageMap();
  const item = map[makeKey(trackSlug, questionNumber)];
  return item ? item.content : '';
}

export function saveQuestionNote(params: {
  trackSlug: string;
  trackTitle: string;
  questionNumber: number;
  questionTitle: string;
  content: string;
}): void {
  if (typeof window === 'undefined') return;
  try {
    const map = getStorageMap();
    const key = makeKey(params.trackSlug, params.questionNumber);

    if (!params.content.trim()) {
      delete map[key];
    } else {
      map[key] = {
        trackSlug: params.trackSlug,
        trackTitle: params.trackTitle,
        questionNumber: params.questionNumber,
        questionTitle: params.questionTitle,
        content: params.content,
        updatedAt: Date.now(),
      };
    }

    localStorage.setItem(NOTES_STORAGE_KEY, JSON.stringify(map));
    window.dispatchEvent(new Event(NOTES_UPDATE_EVENT));
  } catch {}
}

export function deleteQuestionNote(trackSlug: string, questionNumber: number): void {
  if (typeof window === 'undefined') return;
  try {
    const map = getStorageMap();
    delete map[makeKey(trackSlug, questionNumber)];
    localStorage.setItem(NOTES_STORAGE_KEY, JSON.stringify(map));
    window.dispatchEvent(new Event(NOTES_UPDATE_EVENT));
  } catch {}
}

export function getAllNotes(): NoteItem[] {
  const map = getStorageMap();
  return Object.values(map).sort((a, b) => b.updatedAt - a.updatedAt);
}

/**
 * Generate a comprehensive GitHub-flavored Markdown document of all saved user notes
 */
export function exportNotesAsMarkdown(): string {
  const notes = getAllNotes();
  if (notes.length === 0) {
    return '# InterviewHub Personal Study Notes\n\nNo notes saved yet.';
  }

  const dateStr = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  let md = `# InterviewHub - Personal Study Notes & Cheat Sheet\n`;
  md += `*Exported on ${dateStr} • Total Notes: ${notes.length}*\n\n`;
  md += `---\n\n`;

  // Group by Track
  const byTrack: Record<string, NoteItem[]> = {};
  for (const n of notes) {
    if (!byTrack[n.trackTitle]) {
      byTrack[n.trackTitle] = [];
    }
    byTrack[n.trackTitle].push(n);
  }

  for (const [trackTitle, items] of Object.entries(byTrack)) {
    md += `## 📚 ${trackTitle} (${items.length} notes)\n\n`;
    for (const item of items) {
      const url = `https://learn-interview-questions.vercel.app/sections/${item.trackSlug}/${item.questionNumber}`;
      const lastEdited = new Date(item.updatedAt).toLocaleDateString('en-US');

      md += `### [Q${item.questionNumber}: ${item.questionTitle}](${url})\n`;
      md += `*Last edited: ${lastEdited}*\n\n`;
      md += `**My Personal Notes:**\n\n`;
      md += `${item.content}\n\n`;
      md += `---\n\n`;
    }
  }

  md += `\n*Generated by InterviewHub PRO • The Learning Hub Org*\n`;
  return md;
}

/**
 * Trigger client-side browser file download for the exported markdown notes
 */
export function downloadNotesFile(): void {
  if (typeof window === 'undefined') return;
  const mdContent = exportNotesAsMarkdown();
  const blob = new Blob([mdContent], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', `InterviewHub_Personal_Notes_${Date.now()}.md`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
